package itkach.aard2;

import static org.junit.Assert.assertEquals;
import static org.junit.Assert.assertFalse;
import static org.junit.Assert.assertNotNull;
import static org.junit.Assert.assertNull;
import static org.junit.Assert.assertSame;
import static org.junit.Assert.assertTrue;
import static org.junit.Assert.fail;
import static org.robolectric.Shadows.shadowOf;

import android.os.Looper;

import com.fasterxml.jackson.databind.DeserializationFeature;
import com.fasterxml.jackson.databind.ObjectMapper;

import org.junit.After;
import org.junit.Before;
import org.junit.Rule;
import org.junit.Test;
import org.junit.rules.TemporaryFolder;
import org.junit.runner.RunWith;
import org.robolectric.RobolectricTestRunner;
import org.robolectric.annotation.Config;

import java.io.File;
import java.nio.channels.FileChannel;
import java.nio.file.Paths;
import java.text.Normalizer;
import java.util.ArrayList;
import java.util.HashSet;
import java.util.IdentityHashMap;
import java.util.List;
import java.util.Map;
import java.util.Set;

import itkach.slob.Slob;
import itkach.slobber.Slobber;

// The dictionaries are generated by test/mkfixtures.py. movetest-v1, -v2 and -v3
// are versions of one dictionary (same uri); other.slob has a different uri.
@RunWith(RobolectricTestRunner.class)
@Config(application = android.app.Application.class)
public class BlobDescriptorListTest {

    @Rule
    public TemporaryFolder tmp = new TemporaryFolder();

    private final Map<Slob, FileChannel> channels = new IdentityHashMap<>();
    private TestDictionaries dictionaries;
    private File storeDir;
    private DescriptorStore<BlobDescriptor> store;
    private Slob v1;
    private Slob v2;
    private Slob v3;
    private Slob other;

    // Dictionary files as the list sees them: loaded ones in list order, plus
    // ones that are listed but fail to load.
    private static class TestDictionaries implements BlobDescriptorList.Dictionaries {
        final List<Slob> loaded = new ArrayList<>();
        final Set<String> unloadable = new HashSet<>();

        @Override
        public Slob getSlob(String slobId) {
            for (Slob slob : loaded) {
                if (id(slob).equals(slobId)) {
                    return slob;
                }
            }
            return null;
        }

        @Override
        public Slob findSlobByURI(String uri) {
            for (Slob slob : loaded) {
                if (slob.getURI().equals(uri)) {
                    return slob;
                }
            }
            return null;
        }

        @Override
        public List<Slob> getLoadedSlobs() {
            return loaded;
        }

        @Override
        public Set<String> getListedIds() {
            Set<String> ids = new HashSet<>(unloadable);
            for (Slob slob : loaded) {
                ids.add(id(slob));
            }
            return ids;
        }
    }

    @Before
    public void setUp() throws Exception {
        v1 = open("movetest-v1.slob");
        v2 = open("movetest-v2.slob");
        v3 = open("movetest-v3.slob");
        other = open("other.slob");
        dictionaries = new TestDictionaries();
        ObjectMapper mapper = new ObjectMapper();
        mapper.configure(DeserializationFeature.FAIL_ON_UNKNOWN_PROPERTIES, false);
        storeDir = tmp.newFolder("store");
        store = new DescriptorStore<>(mapper, storeDir);
    }

    @After
    public void tearDown() throws Exception {
        for (FileChannel channel : channels.values()) {
            channel.close();
        }
        // Undoes makeStoreReadOnly, so TemporaryFolder can delete it.
        storeDir.setWritable(true);
    }

    private Slob open(String name) throws Exception {
        File file = Paths.get(getClass().getResource("/" + name).toURI()).toFile();
        FileChannel channel = FileChannel.open(file.toPath());
        Slob slob = new Slob(channel, file.toURI().toString());
        channels.put(slob, channel);
        return slob;
    }

    private static String id(Slob slob) {
        return slob.getId().toString();
    }

    // The article's content url, as the app builds it for the pager.
    private static String url(Slob.Blob blob) {
        return "http://127.0.0.1:8013" + Slobber.mkContentURL(blob);
    }

    // The nth article (counting from 0) with exactly this key.
    private static Slob.Blob blob(Slob slob, String key, int n) {
        for (Slob.Blob blob : slob) {
            if (blob.key.equals(key) && n-- == 0) {
                return blob;
            }
        }
        throw new AssertionError("No " + key + " in " + slob.getTags().get("label"));
    }

    private static Slob.Blob blob(Slob slob, String key) {
        return blob(slob, key, 0);
    }

    private static String url(Slob slob, String key) {
        return url(blob(slob, key));
    }

    private static String url(Slob slob, String key, String fragment) {
        Slob.Blob blob = blob(slob, key);
        return url(new Slob.Blob(slob, blob.id, blob.key, fragment));
    }

    private static String nfc(String s) {
        return Normalizer.normalize(s, Normalizer.Form.NFC);
    }

    private static String nfd(String s) {
        return Normalizer.normalize(s, Normalizer.Form.NFD);
    }

    private void load(Slob... slobs) {
        for (Slob slob : slobs) {
            dictionaries.loaded.add(slob);
        }
    }

    // A fresh list over the same store, loaded the way the app does at startup.
    private BlobDescriptorList start() throws InterruptedException {
        BlobDescriptorList list = new BlobDescriptorList(dictionaries, store);
        list.loadAsync();
        awaitLoaded(list);
        return list;
    }

    private void close(BlobDescriptorList list, Slob slob) throws InterruptedException {
        dictionaries.loaded.remove(slob);
        list.moveToLoadedDictionaries();
        awaitLoaded(list);
    }

    // Lookups run on a background thread and post their results to the main
    // looper, which Robolectric only runs when told to.
    private static void awaitLoaded(BlobDescriptorList list) throws InterruptedException {
        long deadline = System.currentTimeMillis() + 5000;
        while (System.currentTimeMillis() < deadline) {
            shadowOf(Looper.getMainLooper()).idle();
            if (!list.isLoading()) {
                return;
            }
            Thread.sleep(5);
        }
        fail("Still loading");
    }

    private List<BlobDescriptor> stored() {
        return store.load(BlobDescriptor.class);
    }

    private static void assertPointsAt(Slob.Blob blob, BlobDescriptor bd) {
        assertEquals(id(blob.owner), bd.slobId);
        assertEquals(blob.id, bd.blobId);
        assertEquals(blob.key, bd.key);
    }

    // The list shows no dictionary for the entry, and it opens nothing.
    private static void assertOrphaned(BlobDescriptorList list, BlobDescriptor bd) {
        assertNull(list.resolveOwner(bd));
        assertNull(list.resolve(bd));
    }

    @Test
    public void articlesWithTheSameKeyAreSeparateEntries() throws Exception {
        load(v1);
        BlobDescriptorList list = start();
        list.add(url(blob(v1, "apple", 0)));
        assertTrue(list.contains(url(blob(v1, "apple", 0))));
        assertFalse(list.contains(url(blob(v1, "apple", 1))));
    }

    @Test
    public void fragmentsAreSeparateEntries() throws Exception {
        load(v1);
        BlobDescriptorList list = start();
        list.add(url(v1, "banana", "later"));
        assertFalse(list.contains(url(v1, "banana")));
        list.add(url(v1, "banana"));
        list.remove(url(v1, "banana"));
        assertFalse(list.contains(url(v1, "banana")));
        assertTrue(list.contains(url(v1, "banana", "later")));
    }

    @Test
    public void movesEntriesWhenTheirDictionaryIsClosed() throws Exception {
        load(v1, v2);
        BlobDescriptorList list = start();
        list.add(url(v1, "apple"));
        list.add(url(v1, "banana", "later"));
        close(list, v1);
        assertTrue(list.contains(url(v2, "apple")));
        assertTrue(list.contains(url(v2, "banana", "later")));
        for (BlobDescriptor bd : list) {
            assertSame(v2, list.resolveOwner(bd));
            assertNotNull(list.resolve(bd));
        }
        List<BlobDescriptor> stored = stored();
        assertEquals(2, stored.size());
        for (BlobDescriptor bd : stored) {
            assertEquals(id(v2), bd.slobId);
        }
    }

    @Test
    public void movesEntriesOnStartupBeforeCountingAsLoaded() throws Exception {
        load(v1, v2);
        start().add(url(v1, "apple"));
        dictionaries.loaded.remove(v1);
        BlobDescriptorList list = new BlobDescriptorList(dictionaries, store);
        String[] seenSlobId = new String[1];
        list.loadAsync();
        list.whenLoaded(() -> seenSlobId[0] = list.get(0).slobId);
        awaitLoaded(list);
        assertEquals(id(v2), seenSlobId[0]);
    }

    @Test
    public void mergesAMovedEntryIntoAnEqualOne() throws Exception {
        load(v1, v2);
        BlobDescriptorList list = start();
        BlobDescriptor old = list.add(url(v1, "banana"));
        old.createdAt = 100;
        old.lastAccess = 500;
        BlobDescriptor current = list.add(url(v2, "banana"));
        current.createdAt = 300;
        current.lastAccess = 200;
        close(list, v1);
        assertEquals(1, list.size());
        assertSame(current, list.get(0));
        List<BlobDescriptor> stored = stored();
        assertEquals(1, stored.size());
        BlobDescriptor merged = stored.get(0);
        assertEquals(current.id, merged.id);
        assertEquals(100, merged.createdAt);
        assertEquals(500, merged.lastAccess);
    }

    @Test
    public void prefersAnExactKeyMatch() throws Exception {
        load(v1, v2);
        BlobDescriptorList list = start();
        // v1's key is composed; v2 has it composed and, sorted first, decomposed.
        assertTrue(v2.indexOf(blob(v2, nfd("naïve"))) < v2.indexOf(blob(v2, nfc("naïve"))));
        list.add(url(v1, nfc("naïve")));
        close(list, v1);
        assertPointsAt(blob(v2, nfc("naïve")), list.get(0));
    }

    @Test
    public void takesTheKeyOfTheArticleMovedTo() throws Exception {
        load(v1, v2);
        BlobDescriptorList list = start();
        list.add(url(v1, nfc("café")));
        close(list, v1);
        assertPointsAt(blob(v2, nfd("café")), list.get(0));
        assertEquals(nfd("café"), stored().get(0).key);
    }

    @Test
    public void recordsAKeyNotFoundAndDoesNotLookItUpAgain() throws Exception {
        load(v1, v2);
        BlobDescriptorList list = start();
        list.add(url(v1, "cherry"));
        close(list, v1);
        BlobDescriptor bd = list.get(0);
        assertPointsAt(blob(v1, "cherry"), bd);
        assertEquals(id(v2), bd.notFoundIn);
        assertEquals(id(v2), stored().get(0).notFoundIn);
        assertOrphaned(list, bd);
        // Nothing left to look up, so the pass doesn't even start.
        list.moveToLoadedDictionaries();
        assertFalse(list.isLoading());
    }

    @Test
    public void doesNotMoveEntriesOfAListedDictionaryThatFailsToLoad() throws Exception {
        load(v1, v2);
        BlobDescriptorList list = start();
        list.add(url(v1, "apple"));
        dictionaries.unloadable.add(id(v1));
        close(list, v1);
        assertPointsAt(blob(v1, "apple"), list.get(0));
        assertOrphaned(list, list.get(0));
        dictionaries.unloadable.remove(id(v1));
        list.moveToLoadedDictionaries();
        awaitLoaded(list);
        assertPointsAt(blob(v2, "apple"), list.get(0));
    }

    @Test
    public void doesNotMoveEntriesToADictionaryWithAnotherUri() throws Exception {
        load(v1, other);
        BlobDescriptorList list = start();
        list.add(url(v1, "apple"));
        close(list, v1);
        BlobDescriptor bd = list.get(0);
        assertPointsAt(blob(v1, "apple"), bd);
        assertNull(bd.notFoundIn);
        assertOrphaned(list, bd);
    }

    @Test
    public void retriesALookupThatFailed() throws Exception {
        load(v1, v2);
        BlobDescriptorList list = start();
        list.add(url(v1, "apple"));
        // Reading v2's articles now fails.
        channels.get(v2).close();
        close(list, v1);
        BlobDescriptor bd = list.get(0);
        assertPointsAt(blob(v1, "apple"), bd);
        assertNull(bd.notFoundIn);
        assertOrphaned(list, bd);
        Slob reopened = open("movetest-v2.slob");
        dictionaries.loaded.set(dictionaries.loaded.indexOf(v2), reopened);
        list.moveToLoadedDictionaries();
        awaitLoaded(list);
        assertPointsAt(blob(reopened, "apple"), list.get(0));
    }

    @Test
    public void runsAgainWhenDictionariesChangeDuringAPass() throws Exception {
        load(v1, v2, v3);
        BlobDescriptorList list = start();
        list.add(url(v1, "apple"));
        // Results of the lookups in v2 are only applied once the main looper
        // runs, which awaitLoaded does: by then v2 is closed too.
        dictionaries.loaded.remove(v1);
        list.moveToLoadedDictionaries();
        assertTrue(list.isLoading());
        close(list, v2);
        assertPointsAt(blob(v3, "apple"), list.get(0));
    }

    @Test
    public void ignoresArticlesOfDictionariesThatAreNotLoaded() throws Exception {
        load(v1);
        BlobDescriptorList list = start();
        String url = url(v1, "apple");
        dictionaries.loaded.remove(v1);
        assertNull(list.createDescriptor(url));
        assertNull(list.add(url));
        assertFalse(list.contains(url));
        assertTrue(list.isEmpty());
        assertTrue(stored().isEmpty());
    }

    @Test
    public void storesTheDictionaryLabel() throws Exception {
        load(v1);
        BlobDescriptorList list = start();
        assertEquals("movetest-v1.slob", list.add(url(v1, "apple")).slobLabel);
        assertEquals("movetest-v1.slob", stored().get(0).slobLabel);
    }

    @Test
    public void aBlankLabelCountsAsNone() throws Exception {
        Slob blank = open("blank-label.slob");
        load(blank);
        BlobDescriptorList list = start();
        assertNull(list.add(url(blank, "apple")).slobLabel);
    }

    @Test
    public void aMovedEntryTakesTheLabelOfItsNewDictionary() throws Exception {
        load(v1, v2);
        BlobDescriptorList list = start();
        list.add(url(v1, "apple"));
        close(list, v1);
        assertEquals("movetest-v2.slob", list.get(0).slobLabel);
        assertEquals("movetest-v2.slob", stored().get(0).slobLabel);
    }

    @Test
    public void anOrphanedEntryKeepsItsLabel() throws Exception {
        load(v1, v2);
        BlobDescriptorList list = start();
        list.add(url(v1, "cherry"));
        close(list, v1);
        assertOrphaned(list, list.get(0));
        assertEquals("movetest-v1.slob", list.get(0).slobLabel);
    }

    // Entries saved before labels were stored.
    private void saveWithoutLabels(Slob slob, String... keys) throws Exception {
        BlobDescriptorList list = start();
        for (String key : keys) {
            BlobDescriptor bd = list.add(url(slob, key));
            bd.slobLabel = null;
            store.save(bd);
        }
    }

    @Test
    public void fillsInLabelsOnLoad() throws Exception {
        load(v1);
        saveWithoutLabels(v1, "apple", "banana");
        BlobDescriptorList list = start();
        for (BlobDescriptor bd : list) {
            assertEquals("movetest-v1.slob", bd.slobLabel);
        }
        for (BlobDescriptor bd : stored()) {
            assertEquals("movetest-v1.slob", bd.slobLabel);
        }
    }

    @Test
    public void fillsInLabelsWhenTheirDictionaryIsLoadedLater() throws Exception {
        load(v1);
        saveWithoutLabels(v1, "apple");
        dictionaries.loaded.remove(v1);
        BlobDescriptorList list = start();
        assertNull(list.get(0).slobLabel);
        load(v1);
        list.moveToLoadedDictionaries();
        awaitLoaded(list);
        assertEquals("movetest-v1.slob", list.get(0).slobLabel);
        assertEquals("movetest-v1.slob", stored().get(0).slobLabel);
    }

    // Makes saving fail, as on a full disk: save writes a temporary file in the
    // store directory first. Tests using it check that the saves did fail:
    // a read-only directory doesn't stop root.
    private void makeStoreReadOnly() {
        assertTrue(storeDir.setWritable(false));
    }

    @Test
    public void loadsEvenWhenLabelsCannotBeSaved() throws Exception {
        load(v1);
        saveWithoutLabels(v1, "apple", "banana");
        makeStoreReadOnly();
        BlobDescriptorList list = start();
        assertEquals(2, list.size());
        for (BlobDescriptor bd : list) {
            assertEquals("movetest-v1.slob", bd.slobLabel);
        }
        for (BlobDescriptor bd : stored()) {
            assertNull(bd.slobLabel);
        }
    }

    @Test
    public void fillsInLabelsLaterEvenWhenTheyCannotBeSaved() throws Exception {
        load(v1);
        saveWithoutLabels(v1, "apple");
        dictionaries.loaded.remove(v1);
        BlobDescriptorList list = start();
        makeStoreReadOnly();
        load(v1);
        list.moveToLoadedDictionaries();
        awaitLoaded(list);
        assertEquals("movetest-v1.slob", list.get(0).slobLabel);
        assertNull(stored().get(0).slobLabel);
    }

    @Test
    public void doesNotSaveARemovedEntryBack() throws Exception {
        load(v1);
        BlobDescriptorList list = start();
        BlobDescriptor bd = list.add(url(v1, "apple"));
        list.remove(url(v1, "apple"));
        bd.lastAccess = 0;
        list.updateLastAccess(bd);
        assertTrue(stored().isEmpty());
    }
}
