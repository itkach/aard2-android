    @Test
    public void readsAKeyNotFoundAsOlderVersionsStoreIt() throws Exception {
        load(v1, v2);
        BlobDescriptor saved = start().add(url(v1, "cherry"));
        saved.notFoundIn = id(v2);
        store.save(saved);
        dictionaries.loaded.remove(v1);
        // Not looked up in v2 again, which would record it as a list.
        BlobDescriptorList list = start();
        BlobDescriptor bd = list.get(0);
        assertEquals(id(v2), bd.notFoundIn);
        assertNull(bd.notFoundInIds);
        // Recording it again, after another version is tried, writes the list.
        dictionaries.loaded.add(v3);
        list.moveToLoadedDictionaries();
        awaitLoaded(list);
        assertEquals(Arrays.asList(id(v2), id(v3)), bd.notFoundInIds);
        assertNull(bd.notFoundIn);
        assertNull(stored().get(0).notFoundIn);
    }

